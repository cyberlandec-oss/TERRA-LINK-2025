import { expect, test } from '@playwright/test';
import { randomBytes } from 'crypto';
import { SUPER_EMAIL } from '../env';

test('Importar parcelas: CSV, vista previa sin guardar, confirmación y ficha con coordenadas; 390 px', async ({ browser }, testInfo) => {
  const suffix = randomBytes(5).toString('hex');
  const email = `importar-${suffix}@e2e.local`;
  const password = randomBytes(15).toString('base64url');
  const superContext = await browser.newContext();
  const sp = await superContext.newPage();
  await sp.goto('/');
  await sp.getByLabel('Correo').fill(SUPER_EMAIL);
  await sp.getByLabel('Contraseña', { exact: true }).fill(process.env.E2E_SUPER_PASSWORD!);
  await sp.getByRole('button', { name: 'Iniciar sesión' }).click();
  await sp.getByLabel('Nombre').fill(`Importación GIS ${suffix}`);
  await sp.getByLabel('Tipo de organización (catálogo provisional, no concede permisos)').selectOption({ label: 'Cooperativa' });
  await sp.getByRole('button', { name: 'Crear organización' }).click();
  await sp.getByRole('link', { name: `Importación GIS ${suffix}` }).click();
  await sp.getByRole('link', { name: 'Incorporar administrador' }).click();
  await sp.getByLabel('Correo', { exact: true }).last().fill(email);
  await sp.getByLabel('Rol').selectOption({ label: 'Administrador de organización' });
  await sp.getByRole('button', { name: 'Generar enlace de invitación' }).click();
  const invite = await sp.getByLabel('Enlace de invitación').inputValue();
  const context = await browser.newContext();
  const page = await context.newPage();
  await page.goto(invite);
  await page.getByLabel('Nombre').fill('Persona');
  await page.getByLabel('Apellido').fill('Importadora');
  await page.getByLabel('Contraseña (mínimo 12 caracteres)').fill(password);
  await page.getByLabel('Repite la contraseña').fill(password);
  await page.getByRole('button', { name: 'Aceptar invitación' }).click();
  await page.getByRole('link', { name: 'Productores', exact: true }).click();
  await page.getByLabel('Código de productor', { exact: true }).fill('GIS-PROD');
  await page.getByLabel('Razón social', { exact: true }).fill('Finca sintética GIS');
  await page.getByRole('button', { name: 'Registrar productor' }).click();
  await expect(page).toHaveURL(/\/productores\/[0-9a-f-]+$/);
  await page.getByRole('link', { name: 'Importar parcelas', exact: true }).click();
  await expect(page).toHaveURL(/\/importar-parcelas$/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Archivo de parcelas').setInputFiles({ name: 'parcelas.csv', mimeType: 'text/csv', buffer: Buffer.from('codigo_parcela;codigo_productor;cultivo;longitud;latitud\nGIS-E2E;GIS-PROD;Cacao;-80,1;-1,2\n') });
  await page.getByRole('button', { name: 'Identificar archivo' }).click();
  await page.getByLabel('CRS de origen (código EPSG)').fill('EPSG:4326');
  await page.getByRole('button', { name: 'Convertir y revisar' }).click();
  await expect(page.getByRole('table', { name: 'Parcelas de la importación' })).toContainText('Se creará');
  await expect(page.getByText('Punto de referencia · Perímetro pendiente', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Mapa de revisión de parcela')).toBeVisible();
  await expect(page.getByText('Verde: geometría propuesta. Naranja: geometría anterior. El mapa no modifica los límites.', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('importar-parcelas-preview-390.png'), fullPage: true });
  await page.getByLabel('Motivo de la importación o corrección').fill('Importación de ejemplo sintético de navegador');
  await page.getByRole('button', { name: 'Confirmar importación', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Importación guardada' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.getByRole('link', { name: 'GIS-E2E', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'GIS-E2E', exact: true })).toBeVisible();
  await context.close();
  await superContext.close();
});
